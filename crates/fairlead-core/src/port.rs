//! Portability (32-portability-and-restructure, R-PORT-020 to R-PORT-023): what a scope
//! requires, the digests that pin it in `gen/scope.lock`, and the snapshot of a portable scope.
//! Pure.
use std::collections::{BTreeMap, BTreeSet};

use fairlead_syntax::ids::Id;

use crate::extract::Corpus;
use crate::registry::{EffectiveItem, ItemId, Lookup, Registry, ScopeId};

/// How a scope comes to require an item.
#[derive(Copy, Clone, PartialEq, Eq, PartialOrd, Ord, Debug)]
pub enum Via {
    Use,
    Extends,
    Authored,
}

impl Via {
    pub fn as_str(self) -> &'static str {
        match self {
            Via::Use => "use",
            Via::Extends => "extends",
            Via::Authored => "authored",
        }
    }
}

/// Whether a scope takes part in portability: it declares `[scope] requires` or is portable.
/// Other scopes keep their 0.2 generated bytes.
pub fn opted_in(reg: &Registry, scope: &ScopeId) -> bool {
    reg.scope(scope)
        .and_then(|s| s.control.as_ref())
        .is_some_and(|c| c.scope_cfg.requires.is_some() || c.scope_cfg.portable)
}

/// R-PORT-020: the items `scope` requires from other scopes: the targets of its files' `use`
/// lines, of its items' `extends=`, and its authored `[scope] requires` (an ID, or `kind.*` for
/// every visible item of the kind). Items of the scope itself are never required.
pub fn required(reg: &Registry, corpus: &Corpus, scope: &ScopeId) -> BTreeMap<ItemId, Via> {
    let mut out: BTreeMap<ItemId, Via> = BTreeMap::new();
    let add = |i: ItemId, v: Via, out: &mut BTreeMap<ItemId, Via>| {
        if i.scope != *scope {
            let e = out.entry(i).or_insert(v);
            *e = (*e).min(v);
        }
    };
    for e in reg.edges() {
        if reg.scope_of(&e.from.path) == Some(scope)
            && corpus.records.contains_key(&e.from.path)
            && let Some(r) = &e.resolved
        {
            add(r.clone(), Via::Use, &mut out);
        }
    }
    for it in reg.items().filter(|it| it.id.scope == *scope) {
        if let Some(crate::registry::FieldValue::Scalar(x)) = it.fields.get("extends")
            && let Ok(id) = Id::parse(x)
            && let Lookup::Found(t) = reg.lookup(scope, &id)
        {
            add(t, Via::Extends, &mut out);
        }
    }
    let authored = reg
        .scope(scope)
        .and_then(|s| s.control.as_ref())
        .and_then(|c| c.scope_cfg.requires.clone())
        .unwrap_or_default();
    for a in authored {
        if let Some(kind) = a.strip_suffix(".*") {
            let ids: Vec<ItemId> = reg
                .view(scope)
                .items
                .keys()
                .filter(|i| i.kind.as_str() == kind)
                .cloned()
                .collect();
            for i in ids {
                add(i, Via::Authored, &mut out);
            }
        } else if let Ok(id) = Id::parse(a.split('@').next().unwrap_or(&a))
            && let Lookup::Found(t) = reg.lookup(scope, &id)
        {
            add(t, Via::Authored, &mut out);
        }
    }
    out
}

/// The authored `[scope] requires` entries that resolve to nothing visible (`HN-R001`).
pub fn unresolved_authored(reg: &Registry, scope: &ScopeId) -> Vec<String> {
    let authored = reg
        .scope(scope)
        .and_then(|s| s.control.as_ref())
        .and_then(|c| c.scope_cfg.requires.clone())
        .unwrap_or_default();
    authored
        .into_iter()
        .filter(|a| {
            if let Some(kind) = a.strip_suffix(".*") {
                return !reg
                    .view(scope)
                    .items
                    .keys()
                    .any(|i| i.kind.as_str() == kind);
            }
            match Id::parse(a.split('@').next().unwrap_or(a)) {
                Ok(id) => !matches!(reg.lookup(scope, &id), Lookup::Found(_)),
                Err(_) => true,
            }
        })
        .collect()
}

fn field_text(v: &crate::registry::FieldValue) -> String {
    match v {
        crate::registry::FieldValue::Scalar(s) => s.clone(),
        crate::registry::FieldValue::List(l) => l.join(","),
    }
}

/// The resolved value of an item as `scope` sees it, one line (policy and fields, sorted).
fn value_text(id: &ItemId, it: &EffectiveItem) -> String {
    let mut t = format!(
        "{}:{}.{}",
        id.scope.0.as_str(),
        id.kind.as_str(),
        id.name.as_str()
    );
    for (k, f) in &it.fields {
        t.push_str(&format!(" {k}={}", field_text(&f.value)));
    }
    t
}

/// R-PORT-022: the resolved-value digest of a required item (12 base32 symbols).
pub fn item_digest(reg: &Registry, scope: &ScopeId, id: &ItemId) -> String {
    let text = reg
        .view(scope)
        .items
        .get(id)
        .map(|it| value_text(id, it))
        .unwrap_or_else(|| format!("{id:?} missing"));
    crate::hash::base32(&crate::hash::hash_raw(text.as_bytes()).0, 12)
}

/// `gen/requires` (R-PORT-020): `<scope>:<kind.name> via=<use|extends|authored>`, sorted.
pub fn requires_body(reg: &Registry, corpus: &Corpus, scope: &ScopeId) -> String {
    let mut out = String::new();
    for (id, via) in required(reg, corpus, scope) {
        out.push_str(&format!(
            "{}:{}.{} via={}\n",
            id.scope.0.as_str(),
            id.kind.as_str(),
            id.name.as_str(),
            via.as_str()
        ));
    }
    out
}

/// The lock lines R-PORT-022 adds to `gen/scope.lock`: `edition=`, `chain dg=`, one
/// `req=<kind.name> from=<scope> dg=<digest> ver=<version>` per required item and, for a
/// portable scope only, one `snap <scope:kind.name> <fields>` line per required item.
pub fn lock_lines(
    reg: &Registry,
    corpus: &Corpus,
    scope: &ScopeId,
    reconciled: crate::version::Version,
    edition: u32,
    chain: &str,
) -> String {
    let mut out = format!("chain dg={chain}\nedition={edition}\n");
    let req = required(reg, corpus, scope);
    for id in req.keys() {
        out.push_str(&format!(
            "req={}.{} from={} dg={} ver={reconciled}\n",
            id.kind.as_str(),
            id.name.as_str(),
            id.scope.0.as_str(),
            item_digest(reg, scope, id)
        ));
    }
    let portable = reg
        .scope(scope)
        .and_then(|s| s.control.as_ref())
        .is_some_and(|c| c.scope_cfg.portable);
    if portable {
        for id in req.keys() {
            if let Some(it) = reg.view(scope).items.get(id) {
                out.push_str(&format!(
                    "snap {}\n",
                    crate::render::sanitize::sanitize_data(&value_text(id, it), 400)
                ));
            }
        }
    }
    out
}

/// One `req=` line of a lock on disk.
#[derive(Clone, PartialEq, Eq, Debug)]
pub struct LockReq {
    pub id: String,
    pub from: String,
    pub dg: String,
}

/// The `req=` lines of a lock on disk.
pub fn parse_lock_reqs(text: &str) -> Vec<LockReq> {
    text.lines()
        .filter_map(|l| {
            let rest = l.strip_prefix("req=")?;
            let mut w = rest.split_whitespace();
            let id = w.next()?.to_owned();
            let kv: BTreeMap<&str, &str> = w.filter_map(|x| x.split_once('=')).collect();
            Some(LockReq {
                id,
                from: kv.get("from")?.to_string(),
                dg: kv.get("dg")?.to_string(),
            })
        })
        .collect()
}

/// R-PORT-021: the scopes that require one another's items in a cycle (sideways `requires`
/// only: an ancestor's item is inherited, not a dependency edge).
pub fn requires_cycles(reg: &Registry, corpus: &Corpus) -> Vec<Vec<ScopeId>> {
    let mut graph: BTreeMap<ScopeId, BTreeSet<ScopeId>> = BTreeMap::new();
    for s in reg.scopes() {
        let chain: Vec<ScopeId> = reg.chain(&s.id).into_iter().cloned().collect();
        for id in required(reg, corpus, &s.id).keys() {
            if !chain.contains(&id.scope) {
                graph
                    .entry(s.id.clone())
                    .or_default()
                    .insert(id.scope.clone());
            }
        }
    }
    let mut cycles = Vec::new();
    let mut seen: BTreeSet<BTreeSet<ScopeId>> = BTreeSet::new();
    for start in graph.keys() {
        // depth-first search for a path back to `start`
        let mut stack: Vec<(ScopeId, Vec<ScopeId>)> = vec![(start.clone(), vec![start.clone()])];
        while let Some((n, path)) = stack.pop() {
            for m in graph.get(&n).into_iter().flatten() {
                if m == start {
                    let set: BTreeSet<ScopeId> = path.iter().cloned().collect();
                    if seen.insert(set) {
                        cycles.push(path.clone());
                    }
                } else if !path.contains(m) {
                    let mut p = path.clone();
                    p.push(m.clone());
                    stack.push((m.clone(), p));
                }
            }
        }
    }
    cycles
}

/// R-PORT-051: `pin <mount scope> commit=<sha or -> dg=<rollup digest>` per mount, sorted.
pub fn pin_lines(mounts: &BTreeMap<String, crate::facts::MountFacts>) -> String {
    let mut out = String::new();
    for (scope, m) in mounts.iter().filter(|(_, m)| m.present) {
        out.push_str(&format!(
            "pin {scope} commit={} dg={}\n",
            m.commit.as_deref().unwrap_or("-"),
            m.digest
        ));
    }
    out
}

/// The `pin` lines of a lock: mount scope to the rest of the line.
pub fn parse_pins(text: &str) -> BTreeMap<String, String> {
    text.lines()
        .filter_map(|l| {
            let rest = l.strip_prefix("pin ")?;
            let (scope, pin) = rest.split_once(' ')?;
            Some((scope.to_owned(), pin.to_owned()))
        })
        .collect()
}

/// R-PORT-041: a `req=` line of a lock on disk whose item no longer resolves from the scope,
/// and whether the portable snapshot carries it.
pub fn unsatisfied(reg: &Registry, scope: &ScopeId, lock: &str) -> Vec<(LockReq, bool)> {
    let snap: BTreeSet<String> = lock
        .lines()
        .filter_map(|l| {
            l.strip_prefix("snap ")?
                .split_whitespace()
                .next()
                .map(str::to_owned)
        })
        .collect();
    parse_lock_reqs(lock)
        .into_iter()
        .filter(|r| {
            let found = Id::parse(&format!("{}:{}", r.from, r.id))
                .ok()
                .is_some_and(|id| matches!(reg.lookup(scope, &id), Lookup::Found(_)));
            !found
        })
        .map(|r| {
            let served = snap.contains(&format!("{}:{}", r.from, r.id));
            (r, served)
        })
        .collect()
}

/// Everything 0.3 adds to a scope's `gen/scope.lock` after `reconciled=`: the `req=` lines of an
/// opted-in scope and, at the root, the mount pins. Shared by `sync` and `seal`.
pub fn lock_extra(
    reg: &Registry,
    corpus: &Corpus,
    facts: &crate::facts::Facts,
    scope: &ScopeId,
    reconciled: crate::version::Version,
) -> String {
    let mut out = String::new();
    if opted_in(reg, scope) {
        let edition = crate::check::builtin::edition_of(reg).0;
        let anc = crate::merkle::ancestor_digest(reg, scope);
        out.push_str(&lock_lines(reg, corpus, scope, reconciled, edition, &anc));
    }
    if scope == reg.root_scope() {
        out.push_str(&pin_lines(&facts.mounts));
    }
    out
}
